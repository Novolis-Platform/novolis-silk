namespace Novolis.Silk;

/// <summary>Mouse buttons. Numeric values match Silk.NET.Input.MouseButton.</summary>
public enum MouseButton
{
    /// <summary>Primary (left) button.</summary>
    Left = 0,

    /// <summary>Secondary (right) button.</summary>
    Right = 1,

    /// <summary>Middle (wheel) button.</summary>
    Middle = 2,
}
